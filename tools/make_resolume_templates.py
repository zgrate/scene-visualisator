#!/usr/bin/env python3
"""Writes src/core/resolume_templates.inc: Arena 7.17 element templates (Screen with an NDI device, Slice, DmxScreen
with a Lumiverse, DmxSlice) cut from the sample Advanced Output file, with every param reset to its default.
Used by the exporter for objects that did not come from an imported file. Run from the repo root."""
import re
import xml.etree.ElementTree as ET

SRC = "tests/fixtures/resolume/arena-7.17-futro-ajki26.xml"
OUT = "src/core/resolume_templates.inc"


def reset(el):
    for p in el.iter():
        if p.tag.startswith("Param") and "value" in p.attrib and "default" in p.attrib:
            p.set("value", p.get("default"))
            mm = p.find("ValueRange[@name='minMax']")
            phase = p.find("PhaseSourceStatic")
            if mm is not None and phase is not None:
                lo, hi, v = float(mm.get("min")), float(mm.get("max")), float(p.get("default"))
                phase.set("phase", "%.20g" % ((v - lo) / (hi - lo) if hi > lo else 0))
    for layers in el.findall("layers"):
        for c in list(layers):
            layers.remove(c)
    return el


root = ET.parse(SRC).getroot()
screens = root.find("ScreenSetup/screens")
screen = next(s for s in screens.findall("Screen") if len(s.findall("layers/Slice")) == 1)
dmx = screens.find("DmxScreen")
parts = {
    "screen": reset(ET.fromstring(ET.tostring(screen))),
    "slice": reset(ET.fromstring(ET.tostring(screen.find("layers/Slice")))),
    "dmx_screen": reset(ET.fromstring(ET.tostring(dmx))),
    "dmx_slice": reset(ET.fromstring(ET.tostring(dmx.find("layers/DmxSlice")))),
}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/make_resolume_templates.py from the Arena 7.17 sample; do not edit.\n")
    for name, el in parts.items():
        text = re.sub(r">\s+<", "><", ET.tostring(el, encoding="unicode").strip())
        f.write('inline constexpr const char *template_%s = R"xml(%s)xml";\n' % (name, text))
